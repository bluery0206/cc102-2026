# VARIABLES

# Creating a variable
# variable_name = value 
name = "John Doe" 

# Accessing the value of a variable
# via the variable name
print(name) 
# Output: John Doe

# Updating the value of a variable
# To update the value of a variable, we can 
# simply assign a new value to it using the assignment operator (=).
name = "Jane Smith"
print(name)
# Output: Jane Smith

# NOTE:
# Lines of code with hashtags (#)
# are called comments in Python. 
# Comments are used to explain 
# the code and does not execute.
 